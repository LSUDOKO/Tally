// QR/NFC payload codec, and fixtures/qr-v1.json: a menu signed and encoded by the SDK that the
// Kotlin app must decode and verify (app/core QrFixtureTest).
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { address } from '@solana/kit';
import * as ed from '@noble/ed25519';
import { describe, expect, it } from 'vitest';
import { base45Decode, base45Encode, computeFloors, fromQr, sha256v, signMenu, toQr, type Item } from '../src';

const OUT = new URL('../../fixtures/qr-v1.json', import.meta.url);
const enc = (s: string) => new TextEncoder().encode(s);

const RAW: [string, number, bigint, string | null][] = [
  ['Oat latte (regular)', 3, 4_500_000n, 'Our most popular. Steamed oat milk, double shot.'],
  ['Oat latte (large)', 3, 5_900_000n, 'A bigger oat latte.'],
  ['Croissant', 0, 3_000_000n, null],
];

async function sample() {
  const secret = new Uint8Array(32).fill(5);
  const items: Item[] = computeFloors(RAW.map(([, category, price], i) => ({ id: sha256v(enc(`tally-item-${i}`)).slice(0, 16), category, price, floor: 0n })));
  const menu = await signMenu({ merchant: address('zNLg5ncNoNWdUHjeMXo1JkTmcQ6biZRPFyFJR7CTBJH'), issuedSlot: 1_000n, expiresSlot: 1_120n, menuNonce: 42n, items }, secret);
  return { secret, payload: { menu, names: RAW.map((r) => r[0]), descriptions: RAW.map((r) => r[3]) } };
}

describe('qr payload', () => {
  it('base45 matches RFC 9285', () => {
    expect(base45Encode(enc('AB'))).toBe('BB8');
    expect(base45Encode(enc('Hello!!'))).toBe('%69 VD92EX0');
    expect(base45Decode('QED8WEX0')).toEqual(enc('ietf!'));
  });

  it('round-trips a signed menu and stays in the QR alphanumeric charset', async () => {
    const { payload } = await sample();
    const qr = toQr(payload);
    expect(qr.startsWith('TALLY:V1:')).toBe(true);
    expect(/^[0-9A-Z $%*+\-./:]+$/.test(qr)).toBe(true);
    const back = fromQr(qr);
    expect(back.names).toEqual(payload.names);
    expect(back.descriptions).toEqual(payload.descriptions);
    expect(back.menu.header).toEqual(payload.menu.header);
    expect(await ed.verifyAsync(back.menu.signature, back.menu.header, back.menu.signerPubkey)).toBe(true);
  });

  it('fixtures/qr-v1.json is current', async () => {
    const { secret, payload } = await sample();
    const text = JSON.stringify(
      { version: 1, note: 'Generated by sdk/test/qr.test.ts', signerPubkeyHex: Buffer.from(await ed.getPublicKeyAsync(secret)).toString('hex'), validAtSlot: 1_050, qr: toQr(payload) },
      null,
      2,
    ) + '\n';
    if (process.env.UPDATE_VECTORS || !existsSync(OUT)) writeFileSync(OUT, text);
    expect(readFileSync(OUT, 'utf8')).toBe(text);
  });
});

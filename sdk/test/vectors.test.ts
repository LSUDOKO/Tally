// Generates fixtures/tx-v1.json: PDAs, pay_offer instruction data and a compiled legacy
// message, so the Kotlin app (app/core) can prove byte equality with this SDK.
// Regenerate with UPDATE_VECTORS=1; otherwise the test asserts the file is current.
import { describe, expect, it } from 'vitest';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import {
  address,
  appendTransactionMessageInstructions,
  compileTransaction,
  createNoopSigner,
  createTransactionMessage,
  getBase64Decoder,
  pipe,
  setTransactionMessageFeePayerSigner,
  setTransactionMessageLifetimeUsingBlockhash,
  type Blockhash,
  type ReadonlyUint8Array,
} from '@solana/kit';
import { findCapsulePda, findConfigPda, findMerchantPda, findKeyRecordPda } from '../src/generated';
import { buildPayOfferInstructions, receiptAddress, type SignedMenu } from '../src/pay';
import { MerkleTree, leafHash, type Item } from '../src/menu';

const OUT = new URL('../../fixtures/tx-v1.json', import.meta.url);
const fx = JSON.parse(readFileSync(new URL('../../fixtures/menu-v1.json', import.meta.url), 'utf8'));
const hex = (b: Uint8Array | ReadonlyUint8Array) => Buffer.from(b).toString('hex');
const unhex = (s: string) => new Uint8Array(Buffer.from(s, 'hex'));

describe('cross-language transaction vectors', () => {
  it('fixtures/tx-v1.json is current', async () => {
    const owner = address('5XPdQGRroRqUycg4rCsLV5ir7owe87jLn7vDGXjkpFqH');
    const agent = address('EE4juH2PvKsanoTvK34yfa5DVxnG7z1DjGyiV1ueYZwg');
    const authority = address(fx.merchant_authority);
    const usdc = address('EPjFWdd5AufqSSqeM2qN1xzybapC8G4wEGGkZwyTDt1v');
    const vault = address('Es9vMFrzaCERmJfrF4H2FYD4KCoNkY11McCe8BenwNYB');
    const payout = address('So11111111111111111111111111111111111111112');
    const [config] = await findConfigPda();
    const [merchant] = await findMerchantPda({ authority });
    const [capsule] = await findCapsulePda({ owner, capsuleId: 1n });
    const [keyRecord] = await findKeyRecordPda({ merchant, signingKey: address(fx.merchant_signing_pubkey) });
    expect(merchant).toBe(fx.merchant_pda);

    const items: Item[] = fx.items.map((x: any) => ({ id: unhex(x.id_hex), category: x.category, price: BigInt(x.price), floor: BigInt(x.floor) }));
    const menu: SignedMenu = {
      merchant,
      issuedSlot: 1000n,
      expiresSlot: 1100n,
      menuNonce: 42n,
      items,
      root: new MerkleTree(items.map(leafHash)).root(),
      header: unhex(fx.header_hex),
      signerPubkey: new Uint8Array(32),
      signature: unhex(fx.signature_hex),
    };
    menu.signerPubkey.set(unhex(fx.ed25519_ix_data_hex).slice(16, 48));
    const ixs = await buildPayOfferInstructions({
      menu,
      index: 1,
      capsule: { address: capsule, owner, vault, mint: usdc },
      agent: createNoopSigner(agent),
      ownerSigner: createNoopSigner(owner),
      payout,
      computeUnitLimit: 60_000,
      lighthouseVaultAfter: 14_100_000n,
      pow: { nonce: unhex('0102030405060708'), slot: 999n },
    });
    const blockhash = '4vJ9JU1bJJE96FWSJKvHsmmFADCg4gpZQff4P3bkLKi' as Blockhash;
    const message = pipe(
      createTransactionMessage({ version: 'legacy' }),
      (m) => setTransactionMessageFeePayerSigner(createNoopSigner(agent), m),
      (m) => setTransactionMessageLifetimeUsingBlockhash({ blockhash, lastValidBlockHeight: 0n }, m),
      (m) => appendTransactionMessageInstructions(ixs, m),
    );
    const tx = compileTransaction(message);
    const vectors = {
      version: 1,
      note: 'Generated by sdk/test/vectors.test.ts from fixtures/menu-v1.json',
      accounts: { owner, agent, authority, usdc, vault, payout },
      pdas: {
        config,
        merchant,
        capsule,
        key_record: keyRecord,
        receipt: await receiptAddress(capsule, merchant, 42n, items[1].id),
      },
      pay_offer: {
        item_index: 1,
        compute_unit_limit: 60000,
        lighthouse_vault_after: 14100000,
        pow_nonce_hex: '0102030405060708',
        pow_slot: 999,
        instruction_data_hex: ixs.map((i) => hex(i.data ?? new Uint8Array())),
        program_ids: ixs.map((i) => i.programAddress),
      },
      message: { blockhash, fee_payer: agent, message_b64: getBase64Decoder().decode(tx.messageBytes) },
    };
    const text = JSON.stringify(vectors, null, 2) + '\n';
    if (process.env.UPDATE_VECTORS || !existsSync(OUT)) writeFileSync(OUT, text);
    expect(readFileSync(OUT, 'utf8')).toBe(text);
  });
});

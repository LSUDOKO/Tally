// fixtures/ix-v1.json: data bytes and account metas for every instruction the Android app
// builds itself, produced by the Codama-generated client. The Kotlin core must match exactly.
// Regenerate with UPDATE_VECTORS=1.
import { describe, expect, it } from 'vitest';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { address, createNoopSigner, getAddressEncoder, getProgramDerivedAddress, type Instruction } from '@solana/kit';
import {
  findCapsulePda,
  findKeyRecordPda,
  findMerchantPda,
  getClaimPromoInstruction,
  getCreateCapsuleInstructionAsync,
  getCreateCapsuleWithSgtInstructionAsync,
  getCloseCapsuleInstruction,
  getFreezeInstruction,
  getFundInstruction,
  getOpenDisputeInstructionAsync,
  getProveFloorFraudInstructionAsync,
  getRegisterMerchantInstructionAsync,
  getSetAgentInstruction,
  getRotateSigningKeyInstruction,
  getSetPowDifficultyInstruction,
  getUpdateRulesInstruction,
  getWithdrawInstruction,
  TALLY_PROGRAM_ADDRESS,
} from '../src/generated';
import { findAssociatedTokenPda, TOKEN_PROGRAM_ADDRESS } from '@solana-program/token';
import { receiptAddress } from '../src/pay';

const OUT = new URL('../../fixtures/ix-v1.json', import.meta.url);
const hex = (b: Uint8Array | ArrayLike<number>) => Buffer.from(b as Uint8Array).toString('hex');
const dump = (ix: Instruction) => ({
  program: ix.programAddress,
  data_hex: hex(ix.data ?? new Uint8Array()),
  accounts: (ix.accounts ?? []).map((a) => ({ address: a.address, signer: a.role >= 2, writable: a.role === 1 || a.role === 3 })),
});

describe('app instruction vectors', () => {
  it('fixtures/ix-v1.json is current', async () => {
    const owner = createNoopSigner(address('5XPdQGRroRqUycg4rCsLV5ir7owe87jLn7vDGXjkpFqH'));
    const agent = address('EE4juH2PvKsanoTvK34yfa5DVxnG7z1DjGyiV1ueYZwg');
    const usdc = address('3GEU4u1stvyvBo2834pgt1vMVsBiDWiZJHsmiWSE8Da5');
    const skr = address('FbMPLRWDgSCVYAMzFZhKxwtsmixpbhszjS9YCxBkgSF2');
    const sgtMint = address('Fd9zbb1tGnvtgT9UL4rCHyP2CCovpVnupcixfpKHbyuX');
    const sgtAccount = address('EYgUGCnLRUdbnikSzApcR4izohmSoHdYs7n7SwUtCxvQ');
    const signingKey = address('8TfJZMw4tMniEs8F6XbjeokVBHpuf2aCnXrXCbRL7Y5T');
    const [capsule] = await findCapsulePda({ owner: owner.address, capsuleId: 1n });
    const [vault] = await findAssociatedTokenPda({ owner: capsule, mint: usdc, tokenProgram: TOKEN_PROGRAM_ADDRESS });
    const [ownerUsdc] = await findAssociatedTokenPda({ owner: owner.address, mint: usdc, tokenProgram: TOKEN_PROGRAM_ADDRESS });
    const [merchant] = await findMerchantPda({ authority: owner.address });
    const [ownerSkr] = await findAssociatedTokenPda({ owner: owner.address, mint: skr, tokenProgram: TOKEN_PROGRAM_ADDRESS });
    const [keyRecord] = await findKeyRecordPda({ merchant, signingKey });
    const rules = { perTxCap: 6_000_000n, dailyCap: 15_000_000n, allowedCategories: [8n, 0n, 0n, 1n << 63n], minMerchantBond: 1_000_000_000n, expirySlot: 999_999_999n, flags: 1 };
    const itemId = new Uint8Array(16).fill(3);
    const receipt = await receiptAddress(capsule, merchant, 42n, itemId);
    const leaf = (n: number) => ({ itemId: new Uint8Array(16).fill(n), category: 3, price: BigInt(n) * 1_000_000n, floor: 3_000_000n });
    const name = new Uint8Array(32);
    name.set(new TextEncoder().encode('Blue Door Coffee'));

    const v = {
      version: 1,
      note: 'Generated by sdk/test/ix-vectors.test.ts (Codama client)',
      inputs: { owner: owner.address, agent, usdc, skr, sgtMint, sgtAccount, signingKey, capsule, merchant, receipt, itemIdHex: hex(itemId) },
      create_capsule: dump(await getCreateCapsuleInstructionAsync({ owner, mint: usdc, capsuleId: 1n, rules, agent })),
      create_capsule_with_sgt: dump(await getCreateCapsuleWithSgtInstructionAsync({ owner, mint: usdc, sgtTokenAccount: sgtAccount, sgtMint, capsuleId: 1n, rules, agent })),
      fund: dump(getFundInstruction({ owner, capsule, mint: usdc, vault, ownerToken: ownerUsdc, amount: 20_000_000n })),
      withdraw: dump(getWithdrawInstruction({ owner, capsule, mint: usdc, vault, ownerToken: ownerUsdc, amount: 5_000_000n })),
      freeze: dump(getFreezeInstruction({ owner, capsule })),
      close_capsule: dump(getCloseCapsuleInstruction({ owner, capsule, mint: usdc, vault, ownerToken: ownerUsdc })),
      set_agent: dump(getSetAgentInstruction({ owner, capsule, newAgent: agent })),
      update_rules: dump(getUpdateRulesInstruction({ owner, capsule, rules })),
      register_merchant: dump(await getRegisterMerchantInstructionAsync({ authority: owner, payout: ownerUsdc, skrMint: skr, authoritySkr: ownerSkr, name, signingKey, bond: 5_000_000_000n })),
      set_pow_difficulty: dump(getSetPowDifficultyInstruction({ authority: owner, merchant, difficulty: 8 })),
      rotate_signing_key: dump(getRotateSigningKeyInstruction({ authority: owner, merchant, oldKeyRecord: keyRecord, newKeyRecord: (await findKeyRecordPda({ merchant, signingKey: agent }))[0], newKey: agent })),
      open_dispute: dump(await getOpenDisputeInstructionAsync({ owner, capsule, receipt, merchant, evidenceHash: new Uint8Array(32).fill(9) })),
      claim_promo: dump(getClaimPromoInstruction({
        owner, capsule, promoId: 7n,
        sgtClaim: (await getProgramDerivedAddress({ programAddress: TALLY_PROGRAM_ADDRESS, seeds: [new TextEncoder().encode('sgt'), getAddressEncoder().encode(sgtMint), new Uint8Array([7, 0, 0, 0, 0, 0, 0, 0])] }))[0],
      })),
      prove_floor_fraud: dump(await getProveFloorFraudInstructionAsync({
        reporter: owner, merchant, skrMint: skr, reporterSkr: ownerSkr, keyRecord,
        fraudRecord: (await getProgramDerivedAddress({ programAddress: TALLY_PROGRAM_ADDRESS, seeds: [new TextEncoder().encode('fraud'), getAddressEncoder().encode(merchant), new Uint8Array(32).fill(5)] }))[0],
        menuRoot: new Uint8Array(32).fill(5), issuedSlot: 100n, expiresSlot: 200n, menuNonce: 42n, itemCount: 9,
        leafA: leaf(3), proofA: [new Uint8Array(32).fill(1)], leafB: leaf(5), proofB: [new Uint8Array(32).fill(2), new Uint8Array(32).fill(4)],
      })),
    };
    const text = JSON.stringify(v, null, 2) + '\n';
    if (process.env.UPDATE_VECTORS || !existsSync(OUT)) writeFileSync(OUT, text);
    expect(readFileSync(OUT, 'utf8')).toBe(text);
  });
});
